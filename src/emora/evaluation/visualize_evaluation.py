"""Stage 10: Visualize existing held-out transformer evaluation reports.

Run from project root after evaluate_transformer.py has produced CSV reports.
Does not load the model or make API calls.
"""
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[3] if 'src' in Path(__file__).parts else Path.cwd()
REPORTS = ROOT / 'reports'
OUT = REPORTS / 'emotion_evaluation'
OUT.mkdir(parents=True, exist_ok=True)

STRATEGIES = {
    'shared_0.30': 'Shared threshold (0.30; chatbot)',
    'per_emotion': 'Saved per-emotion thresholds',
}


def load_report(name):
    path = REPORTS / f'test_{name}_per_emotion.csv'
    if not path.exists():
        raise FileNotFoundError(f'Missing {path}. Run your existing evaluate_transformer.py first.')
    df = pd.read_csv(path, index_col=0)
    # classification_report also contains summary rows; keep only label rows.
    df = df.loc[~df.index.isin(['micro avg', 'macro avg', 'weighted avg', 'samples avg', 'accuracy'])].copy()
    for col in ('precision', 'recall', 'f1-score', 'support'):
        df[col] = pd.to_numeric(df[col], errors='coerce')
    df = df.dropna(subset=['f1-score', 'support'])
    df.index.name = 'emotion'
    return df


def plot_per_emotion(df, name):
    ordered = df.sort_values('f1-score')
    fig, ax = plt.subplots(figsize=(10, max(7, len(ordered) * 0.32)))
    ax.barh(ordered.index, ordered['f1-score'])
    ax.set(xlim=(0, 1), xlabel='F1 score', title=f'Per-emotion F1 — {STRATEGIES[name]}')
    ax.grid(axis='x', alpha=0.2)
    fig.tight_layout()
    fig.savefig(OUT / f'{name}_f1.png', dpi=180)
    plt.close(fig)

    ordered = df.sort_values('support', ascending=False)
    fig, ax = plt.subplots(figsize=(10, max(7, len(ordered) * 0.32)))
    ax.barh(ordered.index[::-1], ordered['support'][::-1])
    ax.set(xlabel='Positive test examples', title=f'Label support — {STRATEGIES[name]}')
    ax.grid(axis='x', alpha=0.2)
    fig.tight_layout()
    fig.savefig(OUT / f'{name}_support.png', dpi=180)
    plt.close(fig)


def main():
    summary_path = REPORTS / 'transformer_test_results.csv'
    if not summary_path.exists():
        raise FileNotFoundError(f'Missing {summary_path}. Run evaluate_transformer.py first.')
    summary = pd.read_csv(summary_path)
    required = {'strategy', 'micro_f1', 'macro_f1', 'precision', 'recall'}
    if not required.issubset(summary.columns):
        raise ValueError(f'Summary is missing columns: {required - set(summary.columns)}')
    summary = summary[summary['strategy'].isin(STRATEGIES)].copy()
    if summary.empty:
        raise ValueError('No recognized threshold strategies found in summary.')

    reports = {}
    for name in summary['strategy']:
        df = load_report(name)
        reports[name] = df
        plot_per_emotion(df, name)
        df.sort_values('f1-score').to_csv(OUT / f'{name}_ranked_emotions.csv')

    metrics = ['micro_f1', 'macro_f1', 'precision', 'recall']
    x = np.arange(len(metrics))
    width = 0.8 / len(summary)
    fig, ax = plt.subplots(figsize=(9, 5))
    for i, (_, row) in enumerate(summary.iterrows()):
        ax.bar(x - 0.4 + width / 2 + i * width,
               [row[m] for m in metrics], width, label=STRATEGIES[row['strategy']])
    ax.set_xticks(x, ['Micro F1', 'Macro F1', 'Micro precision', 'Micro recall'])
    ax.set_ylim(0, 1)
    ax.set_ylabel('Score')
    ax.set_title('Held-out test performance by threshold strategy')
    ax.legend()
    ax.grid(axis='y', alpha=0.2)
    fig.tight_layout()
    fig.savefig(OUT / 'strategy_comparison.png', dpi=180)
    plt.close(fig)

    lines = ['# Emora — Emotion Model Evaluation', '',
             'Source: held-out test CSV reports generated by evaluate_transformer.py.',
             'Scores are multilabel classification metrics, not calibrated confidence.', '',
             '## Overall results', '', '```\n' + summary.to_string(index=False, float_format=lambda x: f'{x:.4f}') + '\n```', '']
    for name, df in reports.items():
        lines += [f'## {STRATEGIES[name]}', '',
                  'Lowest five F1 labels (interpret alongside support):', '',
                  '```\n' + df.nsmallest(5, 'f1-score')[['precision','recall','f1-score','support']].to_string(float_format=lambda x: f'{x:.3f}') + '\n```', '',
                  'Highest five F1 labels:', '',
                  '```\n' + df.nlargest(5, 'f1-score')[['precision','recall','f1-score','support']].to_string(float_format=lambda x: f'{x:.3f}') + '\n```', '']
    lines += ['## Interpretation notes', '',
              '- Shared 0.30 is the current chatbot inference strategy.',
              '- Per-emotion thresholds are a separate evaluated strategy, not automatically deployed.',
              '- Thresholds must be selected on validation data, never optimized using the test set.',
              '- These reports do not contain per-example predictions, so false-positive/false-negative examples cannot be recovered from these CSVs alone.',
              '- This evaluation measures emotion labeling, not clinical safety or conversational helpfulness.', '']
    (OUT / 'evaluation_summary.md').write_text('\n'.join(lines), encoding='utf-8')
    print('Saved evaluation report and charts to:', OUT)
    for path in sorted(OUT.iterdir()):
        print(' -', path.name)


if __name__ == '__main__':
    main()
